// Bundles the repo dataset into src/data.generated.ts so the server needs no network at runtime.
// Reads ../data/latest/<CUR>.json, ../data/country_market.csv, ../data/rates/<date>.csv and ../CHANGELOG.md.
// Usage: node scripts/build-data.mjs   (runs automatically before every build)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = join(here, '..', '..')
const read = (p) => readFileSync(join(repo, p), 'utf8').replace(/^﻿/, '')

// Meta's free allowance for service messages, per business phone number per calendar month (CHANGELOG 2026-10-01).
// The CSVs carry the service rate; this rule is not in Meta's files, so it lives here and in packages/scripts.
const FREE_SERVICE = { per_number_per_month: 1000, since: '2026-10-01' }

function parseCsv(text) {
  const [head, ...rows] = text.trim().split(/\r?\n/).map((line) => {
    const out = []
    let cur = ''
    let q = false
    for (const ch of line) {
      if (ch === '"') q = !q
      else if (ch === ',' && !q) {
        out.push(cur)
        cur = ''
      } else cur += ch
    }
    out.push(cur)
    return out
  })
  return rows.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ''])))
}

const index = JSON.parse(read('rates.json'))
const currencies = {}
for (const c of index.currencies) {
  const j = JSON.parse(read(c.latest_json))
  if (j.markets.length < 40 || !j.markets.some((m) => m.market === 'Other')) throw new Error(`${c.code}: looks wrong`)
  currencies[c.code] = j.markets.map((m) => ({
    market: m.market,
    type: m.type,
    marketing: m.marketing,
    utility: m.utility,
    authentication: m.authentication,
    authentication_international: m.authentication_international,
    service: m.service,
  }))
}
const first = JSON.parse(read(index.currencies[0].latest_json))

const countries = parseCsv(read(index.country_market)).map((r) => ({
  iso2: r.iso2,
  country: r.country,
  market: r.market,
  calling_code: r.calling_code,
}))
if (countries.length < 100) throw new Error('country_market.csv looks wrong')

// Rate changes between consecutive cards, all currencies (small: only changed cells are kept).
const dates = readdirSync(join(repo, 'data/rates')).filter((f) => f.endsWith('.csv')).map((f) => f.slice(0, 10)).sort()
const keyed = (d) =>
  new Map(parseCsv(read(`data/rates/${d}.csv`)).map((r) => [`${r.currency}|${r.market}|${r.category}`, r.rate]))
// CHANGELOG sections "## <date>" hold the human summary; the table under "Earlier quarters" holds Meta's counts.
const changelog = read('CHANGELOG.md')
const sections = changelog.split(/^## /m).slice(1)
function notesFor(date) {
  const s = sections.find((x) => x.startsWith(date))
  if (!s) return []
  const body = s.slice(s.indexOf('\n') + 1)
  // One note per paragraph or bullet; wrapped lines are joined.
  return body
    .split(/\n(?=- )|\n\s*\n/)
    .map((x) => x.replace(/^- /, '').replace(/\s*\n\s*/g, ' ').trim())
    .filter(Boolean)
}
const versions = []
let prev = null
for (const d of dates) {
  const cur = keyed(d)
  let changes = null
  if (prev) {
    changes = []
    for (const k of new Set([...prev.map.keys(), ...cur.keys()])) {
      const [currency, market, category] = k.split('|')
      const a = prev.map.get(k) ?? null
      const b = cur.get(k) ?? null
      if (a !== b) changes.push({ currency, market, category, old: a === null ? null : Number(a), new: b === null ? null : Number(b) })
    }
  }
  versions.push({ effective_date: d, previous: prev ? prev.date : null, notes: notesFor(d), changes })
  prev = { date: d, map: cur }
}
const earlier = [...changelog.matchAll(/^\| (\d{4}-\d{2}-\d{2}) \| (\d+) \|$/gm)].map((m) => ({
  effective_date: m[1],
  updated_rates_stated_by_meta: Number(m[2]),
}))

const data = {
  effective_date: index.latest_effective_date,
  checked_on: first.checked_on,
  source: first.source,
  license: first.license,
  attribution: first.attribution,
  free_service: FREE_SERVICE,
  currencies,
  countries,
  versions,
  earlier_quarters: earlier,
}
writeFileSync(
  join(here, '..', 'src', 'data.generated.ts'),
  `// Generated by scripts/build-data.mjs from the repo dataset. Do not edit.\nimport type { Dataset } from './types.js'\n\nexport const data: Dataset = ${JSON.stringify(data)}\n`,
)
console.log(
  `bundled ${Object.keys(currencies).length} currencies, ${countries.length} countries, ${versions.length} card(s), effective ${data.effective_date}`,
)
