// Regenerates the bundled rate data for both packages from the repo dataset (data/latest/EUR.csv).
// Usage: node scripts/build-data.mjs [csv-url-or-local-path]   (default: ../data/latest/EUR.csv in this repo)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = process.argv[2] || join(root, '..', 'data/latest/EUR.csv')

function parseLine(line) {
  const out = []
  let cur = ''
  let q = false
  for (const ch of line) {
    if (ch === '"') q = !q
    else if (ch === ',' && !q) {
      out.push(cur)
      cur = ''
    } else cur += ch
  }
  out.push(cur)
  return out
}

const text = /^https?:/.test(src)
  ? await (await fetch(src, { headers: { 'User-Agent': 'Mozilla/5.0 (whatsapp-pricing data build)' } })).text()
  : readFileSync(src, 'utf8')
const [head, ...rows] = text.replace(/^﻿/, '').trim().split(/\r?\n/).map(parseLine)
const num = (v) => (v === '' ? null : Number(v))
const markets = rows.map((r) => {
  const o = Object.fromEntries(head.map((h, i) => [h, r[i]]))
  return {
    market: o.market,
    type: o.type,
    iso_codes: o.iso_codes ? o.iso_codes.split(/\s+/) : [],
    calling_code: o.calling_code || null,
    marketing: num(o.marketing),
    utility: num(o.utility),
    authentication: num(o.authentication),
    authentication_international: num(o.authentication_international),
    service: num(o.service),
  }
})
const first = Object.fromEntries(head.map((h, i) => [h, rows[0][i]]))
for (const m of markets) {
  for (const k of ['marketing', 'utility', 'authentication', 'service']) {
    if (typeof m[k] !== 'number' || Number.isNaN(m[k])) throw new Error(`Bad ${k} for ${m.market}`)
  }
}
if (markets.length < 40 || !markets.some((m) => m.market === 'Other')) throw new Error('CSV looks wrong')

const data = {
  currency: first.currency,
  effective_date: first.effective_date,
  checked_on: first.checked_on,
  source: first.source,
  free_service_per_number: 1000,
  license: 'CC BY 4.0. Rates: Meta (source above). Compiled by Tobachat.',
  markets,
}
const json = JSON.stringify(data, null, 2) + '\n'
writeFileSync(join(root, 'js/data.json'), json)
writeFileSync(join(root, 'python/src/whatsapp_pricing/data.json'), json)
writeFileSync(
  join(root, 'js/src/data.ts'),
  `// Generated by scripts/build-data.mjs. Do not edit.\nimport type { RateData } from './types.js'\n\nexport const data: RateData = ${JSON.stringify(data, null, 2)}\n`,
)
console.log(`${markets.length} markets, effective ${data.effective_date}, checked ${data.checked_on}`)
